//! Writes `crates/stu/data/types.txt` from OWLib's generated STU type files
//! (`TankLib/STU/Types` at the pinned OWLib revision, MIT):
//!
//! ```text
//! cargo run -p lucy-stu --bin gen-types -- <OWLib>/TankLib/STU/Types crates/stu/data/types.txt
//! ```
//!
//! The output keeps what the reader needs, one item per line:
//! `class <hash> <name> <parent>`, then its own fields as
//! `field <hash> <name> <C# type> <reader> [default]` (reader `embed`,
//! `inline` or `-`), and `enum <name> <underlying type>`. A field's declared
//! initializer becomes its default: a number (enum members resolved), `v:`
//! and comma-separated floats, or `s:` and the text of a string. The C# types
//! are resolved when the table loads.

use std::{
    collections::BTreeMap,
    env, fs,
    io::{self, Write},
    path::{Path, PathBuf},
};

struct Class {
    hash: u32,
    parent: String,
    fields: Vec<Field>,
}

struct Field {
    hash: u32,
    name: String,
    kind: String,
    reader: &'static str,
    default: Option<String>,
}

#[derive(Default)]
struct Enums {
    underlying: BTreeMap<String, String>,
    members: BTreeMap<(String, String), String>,
}

fn main() -> io::Result<()> {
    let mut args = env::args().skip(1);
    let (Some(types), Some(output)) = (args.next(), args.next()) else {
        eprintln!("usage: gen-types <OWLib>/TankLib/STU/Types <output>");
        std::process::exit(2);
    };
    let mut classes = BTreeMap::new();
    let mut enums = Enums::default();
    let mut files = Vec::new();
    collect(Path::new(&types), &mut files)?;
    files.sort();
    for file in files {
        parse(&fs::read_to_string(&file)?, &mut classes, &mut enums);
    }
    let mut out = io::BufWriter::new(fs::File::create(&output)?);
    writeln!(
        out,
        "# Generated by `cargo run -p lucy-stu --bin gen-types` from OWLib's TankLib/STU/Types (MIT)."
    )?;
    for (name, underlying) in &enums.underlying {
        writeln!(out, "enum {name} {underlying}")?;
    }
    for (name, class) in &classes {
        writeln!(out, "class {:08X} {name} {}", class.hash, class.parent)?;
        for field in &class.fields {
            write!(
                out,
                "field {:08X} {} {} {}",
                field.hash, field.name, field.kind, field.reader
            )?;
            if let Some(default) = &field.default {
                write!(out, " {}", literal(default, &field.kind, &enums))?;
            }
            writeln!(out)?;
        }
    }
    out.flush()?;
    eprintln!(
        "{} classes, {} enums -> {output}",
        classes.len(),
        enums.underlying.len()
    );
    Ok(())
}

fn collect(folder: &Path, files: &mut Vec<PathBuf>) -> io::Result<()> {
    for entry in fs::read_dir(folder)? {
        let path = entry?.path();
        if path.is_dir() {
            collect(&path, files)?;
        } else if path.extension().is_some_and(|extension| extension == "cs") {
            files.push(path);
        }
    }
    Ok(())
}

/// The files are TankLibHelper's output: an attribute line, then the
/// declaration it belongs to.
fn parse(text: &str, classes: &mut BTreeMap<String, Class>, enums: &mut Enums) {
    let mut class_hash = None;
    let mut enum_pending = false;
    let mut current: Option<String> = None;
    let mut current_enum: Option<String> = None;
    let mut field: Option<(u32, &'static str)> = None;
    for line in text.lines().map(str::trim) {
        if let Some(rest) = line.strip_prefix("[STU(") {
            class_hash = hex_before(rest, ',');
        } else if line.starts_with("[STUEnum(") {
            enum_pending = true;
        } else if let Some(rest) = line.strip_prefix("public class ") {
            let (name, parent) = match rest.split_once(':') {
                Some((name, parent)) => (name.trim(), parent.trim()),
                None => (rest.trim(), "-"),
            };
            current = None;
            current_enum = None;
            if let Some(hash) = class_hash.take() {
                classes.insert(
                    name.to_owned(),
                    Class {
                        hash,
                        parent: parent.to_owned(),
                        fields: Vec::new(),
                    },
                );
                current = Some(name.to_owned());
            }
        } else if let Some(rest) = line.strip_prefix("public enum ") {
            current = None;
            current_enum = None;
            if std::mem::take(&mut enum_pending)
                && let Some((name, underlying)) = rest.split_once(':')
            {
                let name = name.trim().to_owned();
                enums
                    .underlying
                    .insert(name.clone(), underlying.trim().to_owned());
                current_enum = Some(name);
            }
        } else if let Some(rest) = line.strip_prefix("[STUField(") {
            if let Some(enumeration) = &current_enum {
                // An enum member: `[STUField(0x..)] Name = value,`
                if let Some((_, member)) = rest.split_once(']')
                    && let Some((member, value)) = member.split_once('=')
                {
                    enums.members.insert(
                        (enumeration.clone(), member.trim().to_owned()),
                        value.trim().trim_end_matches(',').trim().to_owned(),
                    );
                }
                continue;
            }
            let reader = if rest.contains("EmbeddedInstanceFieldReader") {
                "embed"
            } else if rest.contains("InlineInstanceFieldReader") {
                "inline"
            } else {
                "-"
            };
            field = hex_before(rest, ',')
                .or_else(|| hex_before(rest, ')'))
                .map(|hash| (hash, reader));
        } else if let Some(rest) = line.strip_prefix("public ") {
            let Some((hash, reader)) = field.take() else {
                continue;
            };
            let (declaration, default) = match rest.split_once('=') {
                Some((declaration, default)) => (
                    declaration,
                    Some(default.trim().trim_end_matches(';').trim().to_owned()),
                ),
                None => (rest.trim_end_matches(';'), None),
            };
            let mut words = declaration.split_whitespace();
            let (Some(kind), Some(name)) = (words.next(), words.next()) else {
                continue;
            };
            if let Some(class) = current.as_ref().and_then(|name| classes.get_mut(name)) {
                class.fields.push(Field {
                    hash,
                    name: name.to_owned(),
                    kind: kind.to_owned(),
                    reader,
                    default,
                });
            }
        }
    }
}

/// A C# initializer as the type table writes it.
fn literal(text: &str, kind: &str, enums: &Enums) -> String {
    // A cast such as `(Enum_DAE586FD)0x1` keeps its number.
    let text = match text.strip_prefix('(').and_then(|rest| rest.split_once(')')) {
        Some((_, value)) => value.trim(),
        None => text,
    };
    if let Some(text) = text.strip_prefix('"') {
        return format!("s:{}", text.strip_suffix('"').expect("a closed string"));
    }
    if let Some(arguments) = text.strip_prefix("new ") {
        let inside = arguments
            .split_once('(')
            .and_then(|(_, rest)| rest.strip_suffix(')'))
            .unwrap_or_else(|| panic!("constructor default {text}"));
        let floats: Vec<String> = inside.split(',').map(|part| number(part.trim())).collect();
        return format!("v:{}", floats.join(","));
    }
    if let Some((enumeration, member)) = text.split_once('.')
        && enums.underlying.contains_key(enumeration)
    {
        let value = enums
            .members
            .get(&(enumeration.to_owned(), member.to_owned()))
            .unwrap_or_else(|| panic!("enum member {text} of field type {kind}"));
        return number(value);
    }
    number(text)
}

/// A C# number literal (hex, float suffix, sign) in plain decimal.
fn number(text: &str) -> String {
    let (negative, digits) = match text.strip_prefix('-') {
        Some(digits) => (true, digits),
        None => (false, text),
    };
    if let Some(hex) = digits.strip_prefix("0x") {
        let value = u64::from_str_radix(hex, 16).unwrap_or_else(|_| panic!("number {text}"));
        return if negative {
            format!("-{value}")
        } else {
            value.to_string()
        };
    }
    // A float literal's `f` suffix; hex digits above were left alone.
    let text = text.trim_end_matches(['f', 'F']);
    text.parse::<f64>()
        .unwrap_or_else(|_| panic!("number {text}"));
    text.to_owned()
}

fn hex_before(text: &str, end: char) -> Option<u32> {
    let value = text.split(end).next()?.trim();
    u32::from_str_radix(value.strip_prefix("0x")?, 16).ok()
}
